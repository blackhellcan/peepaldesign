// Token exporters (architecture Part 3 §3.2, developer hand-offs). Every format is
// generated from one canonical token list so they cannot drift apart. Inferred
// palette clusters are left out by default: exports carry what the team declared
// plus the scales and roles GapScan derived, each marked with its provenance.
import {parseColor, toHex} from '@gapscan/normalize';
import type {ExtractedDesignSystem, Token} from '@gapscan/schema';

export type ExportFormat = 'dtcg' | 'css' | 'tailwind4' | 'scss';
export const EXPORT_FORMATS: Record<ExportFormat, {file: string; type: string; label: string}> = {
  dtcg: {file: 'tokens.json', type: 'application/json', label: 'W3C design tokens (DTCG)'},
  css: {file: 'tokens.css', type: 'text/css', label: 'CSS custom properties'},
  tailwind4: {file: 'theme.css', type: 'text/css', label: 'Tailwind v4 @theme'},
  scss: {file: '_tokens.scss', type: 'text/x-scss', label: 'SCSS variables'},
};

export type ExportOptions = {includeInferredPalette?: boolean; includeProvenance?: boolean};
type Entry = {path: string[]; token: Token; value: string; reference?: string[]};

const DTCG_TYPE: Partial<Record<Token['type'], string>> = {color: 'color', dimension: 'dimension', radius: 'dimension', fontFamily: 'fontFamily', fontWeight: 'fontWeight', shadow: 'shadow', duration: 'duration', cubicBezier: 'cubicBezier'};
const segment = (text: string) => text.replace(/^[-$@]+/, '').replace(/[^a-zA-Z0-9]+/g, '-').replace(/^-|-$/g, '').toLowerCase() || 'token';
// `--brand-primary` → ['brand', 'primary']; `color.primary` stays as is.
const pathOf = (token: Token) => token.path.includes('.') && !token.path.startsWith('--') ? token.path.split('.').map(segment) : segment(token.path).split('-').filter(Boolean);

function entries(eds: ExtractedDesignSystem, {includeInferredPalette = false}: ExportOptions): Entry[] {
  const byPath = new Map(eds.tokens.map(t => [t.path, t]));
  return eds.tokens
    .filter(t => t.status !== 'unresolved' && (includeInferredPalette || !t.path.startsWith('color.palette.')))
    .map(token => {
      const value = String(token.value), target = token.aliasOf && byPath.get(token.aliasOf);
      const normalized = token.type === 'color' && parseColor(value) ? toHex(parseColor(value)!) : value;
      return {path: pathOf(token), token, value: normalized, ...(target ? {reference: pathOf(target)} : {})};
    })
    // Two source names can normalise to one path; the most confident wins.
    .sort((a, b) => b.token.confidence - a.token.confidence)
    .filter((e, i, all) => all.findIndex(x => x.path.join('.') === e.path.join('.')) === i)
    .sort((a, b) => a.path.join('.').localeCompare(b.path.join('.')));
}

const cssName = (path: string[]) => `--${path.join('-')}`;
const provenance = (t: Token) => t.confidence >= 0.8 ? 'confirmed' : t.confidence >= 0.5 ? 'likely' : 'inferred';

export function exportTokens(eds: ExtractedDesignSystem, format: ExportFormat, options: ExportOptions = {}): string {
  const list = entries(eds, options), withProvenance = options.includeProvenance ?? true;
  const header = `Generated by GapScan from extraction ${eds.id} (version ${eds.version}, fingerprint ${eds.fingerprint.slice(0, 12)}). Values marked inferred were derived from usage, not declared.`;
  switch (format) {
    case 'dtcg': {
      const root: Record<string, unknown> = {$description: header};
      for (const e of list) {
        let node = root;
        for (const key of e.path.slice(0, -1)) {
          const next = node[key];
          // A group cannot also be a token in DTCG; a clashing token moves under `_`.
          if (next && typeof next === 'object' && '$value' in (next as object)) node[key] = {_: next};
          node = (node[key] ??= {}) as Record<string, unknown>;
        }
        const leaf = e.path.at(-1)!, type = DTCG_TYPE[e.token.type];
        const token: Record<string, unknown> = {$value: e.reference ? `{${e.reference.join('.')}}` : e.value, ...(type ? {$type: type} : {})};
        if (withProvenance) token.$extensions = {'com.gapscan': {confidence: provenance(e.token), sourcePath: e.token.path, evidence: e.token.evidence.length, ...(e.token.modes ? {modes: e.token.modes} : {})}};
        if (node[leaf] && typeof node[leaf] === 'object' && !('$value' in (node[leaf] as object))) (node[leaf] as Record<string, unknown>)._ = token; else node[leaf] = token;
      }
      return JSON.stringify(root, null, 2) + '\n';
    }
    case 'css': {
      const lines = list.map(e => `  ${cssName(e.path)}: ${e.reference ? `var(${cssName(e.reference)})` : e.value};${withProvenance && provenance(e.token) === 'inferred' ? ' /* inferred */' : ''}`);
      const modes = new Map<string, string[]>();
      for (const e of list) for (const [mode, value] of Object.entries(e.token.modes ?? {})) if (!/^light$/i.test(mode)) modes.set(mode, [...(modes.get(mode) ?? []), `  ${cssName(e.path)}: ${value};`]);
      return `/* ${header} */\n:root {\n${lines.join('\n')}\n}\n${[...modes].map(([mode, l]) => `\n[data-theme="${segment(mode)}"] {\n${l.join('\n')}\n}\n`).join('')}`;
    }
    case 'tailwind4': {
      // Tailwind v4 namespaces: --color-*, --spacing-*, --radius-*, --shadow-*, --font-*, --text-*.
      const ns = (e: Entry): string | null => {
        const tail = e.path[0] === 'color' || e.path[0] === 'space' || e.path[0] === 'radius' || e.path[0] === 'shadow' || e.path[0] === 'font' ? e.path.slice(1) : e.path;
        if (e.token.type === 'color') return `--color-${tail.join('-')}`;
        if (e.token.type === 'radius') return `--radius-${tail.join('-')}`;
        if (e.token.type === 'shadow') return `--shadow-${tail.join('-')}`;
        if (e.token.type === 'fontFamily') return `--font-${tail.filter(s => s !== 'family').join('-') || 'sans'}`;
        if (e.path[0] === 'font' && e.path[1] === 'size') return `--text-${e.path.slice(2).join('-')}`;
        if (e.path[0] === 'space') return `--spacing-${tail.join('-')}`;
        return null;
      };
      const lines = list.flatMap(e => { const name = ns(e); return name ? [`  ${name}: ${e.reference ? `var(${ns({...e, path: e.reference}) ?? cssName(e.reference)})` : e.value};`] : []; });
      return `/* ${header} */\n@import "tailwindcss";\n\n@theme {\n${[...new Set(lines)].join('\n')}\n}\n`;
    }
    case 'scss':
      return `// ${header}\n${list.map(e => `$${e.path.join('-')}: ${e.reference ? `$${e.reference.join('-')}` : e.value};`).join('\n')}\n`;
  }
}
